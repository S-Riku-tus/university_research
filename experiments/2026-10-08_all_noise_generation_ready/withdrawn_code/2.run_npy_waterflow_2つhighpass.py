def _pcm_to_float(data):
    """Convert scipy WAV data to a librosa-like floating representation."""
    data = np.asarray(data)
    if np.issubdtype(data.dtype, np.floating):
        return data.astype(np.float64, copy=False)
    if data.dtype == np.uint8:
        return (data.astype(np.float64) - 128.0) / 128.0
    info = np.iinfo(data.dtype)
    scale = float(max(abs(info.min), info.max))
    return data.astype(np.float64) / scale


def _load_resampled_wav(path, target_sr=44100, first_channel=False):
    """Load one WAV deterministically and resample it when required."""
    source_sr, data = wavfile.read(path, mmap=True)
    data = _pcm_to_float(data)
    if data.ndim > 1:
        data = data[:, 0] if first_channel else data.mean(axis=1)
    if int(source_sr) != int(target_sr):
        divisor = gcd(int(source_sr), int(target_sr))
        data = signal.resample_poly(
            data,
            int(target_sr) // divisor,
            int(source_sr) // divisor,
        )
    return np.asarray(data, dtype=float), int(target_sr)


def _load_and_filter(path, first_channel=False):
    data, samplerate = _load_resampled_wav(
        path, first_channel=first_channel
    )
    return highpass_filter(
        data[:AUDIO_SAMPLES_USED],
        samplerate,
        FILTER_PASS_HZ,
        FILTER_STOP_HZ,
        FILTER_PASS_LOSS_DB,
        FILTER_STOP_ATTENUATION_DB,
    )


def _build_source_plans(chunk_seconds):
    plans = []
    for experiment_name in EXPERIMENT_NAMES:
        context = build_experiment_context(
            experiment_name=experiment_name,
            base_experiment_dir=BASE_EXPERIMENT_DIR,
            recording_dir_name=RECORDING_DIR_NAME,
            waterflow_path=WATERFLOW_PATH,
            save_date=SAVE_DATE,
            chunk_seconds=chunk_seconds,
            script_path=__file__,
        )
        folder_path = context["folder_path"]
        if not os.path.isdir(folder_path):
            raise FileNotFoundError(
                f"recording folder not found: {folder_path}"
            )
        wav_files = get_sorted_wav_files(folder_path)
        wav_paths = [os.path.join(folder_path, name) for name in wav_files]
        plans.append(
            {
                "experiment_name": experiment_name,
                "context": context,
                "wav_files": wav_files,
                "wav_paths": wav_paths,
            }
        )
    return plans


def _estimate_global_reference_rms(source_paths):
    """Return one scalar derived once from all configured source WAVs."""
    rms_by_path = {}
    for index, path in enumerate(source_paths, start=1):
        filtered = _load_and_filter(path)
        rms_by_path[path] = float(np.sqrt(np.mean(filtered**2)))
        print(
            f"reference RMS {index}/{len(source_paths)}: "
            f"{os.path.basename(path)}"
        )
    if not rms_by_path:
        raise ValueError("No source WAVs were found for global RMS estimation.")
    return float(np.median(list(rms_by_path.values()))), rms_by_path


def _resolve_reference_rms(source_paths):
    if not REFERENCE_RMS_MANIFEST_PATHS:
        reference_rms, rms_by_path = _estimate_global_reference_rms(source_paths)
        if not np.isfinite(reference_rms) or reference_rms <= 0:
            raise ValueError("Reference RMS must be finite and positive.")
        return reference_rms, rms_by_path, [], (
            f"median filtered RMS of {len(source_paths)} source WAVs; "
            "one scalar shared by every sample; not calibrated SPL"
        )

    records = []
    expected_filter = {
        "fp_hz": FILTER_PASS_HZ, "fs_hz": FILTER_STOP_HZ,
        "gpass_db": FILTER_PASS_LOSS_DB, "gstop_db": FILTER_STOP_ATTENUATION_DB,
    }
    for relative_path in REFERENCE_RMS_MANIFEST_PATHS:
        path = os.path.join(REPO_ROOT, relative_path)
        with open(windows_long_path(path), "rb") as file:
            raw = file.read()
        manifest = json.loads(raw.decode("utf-8-sig"))
        noise = manifest["noise"]
        reference_rms = float(noise["fixed_reference_signal_rms"])
        if noise["scaling_mode"] != "fixed_global_rms" or not np.isfinite(reference_rms) or reference_rms <= 0:
            raise ValueError(f"Invalid fixed reference RMS in {path}")
        if any(manifest["highpass_filter"].get(key) != value for key, value in expected_filter.items()):
            raise ValueError(f"Reference high-pass settings differ in {path}")
        records.append({"path": os.path.relpath(path, REPO_ROOT),
            "sha256": hashlib.sha256(raw).hexdigest(), "reference_rms": reference_rms})
    reference_rms = records[0]["reference_rms"]
    if any(not np.isclose(record["reference_rms"], reference_rms, rtol=1e-12, atol=0) for record in records):
        raise ValueError("Reference manifests do not agree on the shared RMS.")
    provenance = "fixed_global_rms copied from reference manifests: " + "; ".join(record["path"] for record in records)
    return reference_rms, {}, records, provenance + "; not calibrated SPL"


def _write_reference_manifest(context, reference_rms, rms_by_path, reference_records=None):
    os.makedirs(windows_long_path(context["base_npy_save_folder_path"]), exist_ok=True)
    manifest = {
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "reference_rms": reference_rms,
        "reference_scope": (
            "shared RMS copied from reference dataset manifests"
            if reference_records else "all configured source WAVs across the configured experiments"
        ),
        "reference_source_manifests": reference_records or [],
        "source_count": len(rms_by_path),
        "label_or_individual_source_used_for_noise_level": False,
        "calibrated_spl": False,
        "filter": {
            "pass_hz": FILTER_PASS_HZ,
            "stop_hz": FILTER_STOP_HZ,
            "pass_loss_db": FILTER_PASS_LOSS_DB,
            "stop_attenuation_db": FILTER_STOP_ATTENUATION_DB,
        },
        "source_rms": [
            {
                "path": os.path.relpath(path, REPO_ROOT),
                "filtered_rms": rms,
            }
            for path, rms in sorted(rms_by_path.items())
        ],
    }
    path = os.path.join(
        context["base_npy_save_folder_path"],
        "global_reference_manifest_noise.json" if reference_records and None not in REFERENCE_SNR_DB else "global_reference_manifest.json",
    )
    with open_text(path, "w", encoding="utf-8") as file:
        json.dump(manifest, file, ensure_ascii=False, indent=2)


def run_all_experiments():
    if not os.path.isfile(WATERFLOW_PATH):
        raise FileNotFoundError(f"water-flow WAV not found: {WATERFLOW_PATH}")

    print("Preloading and filtering the shared water-flow recording...")
    filtered_waterflow_noise = _load_and_filter(
        WATERFLOW_PATH, first_channel=True
    )

    for chunk_i, chunk_seconds in enumerate(CHUNK_SECONDS_LIST, start=1):
        print(
            f"========== chunk {chunk_i}/{len(CHUNK_SECONDS_LIST)}: "
            f"{chunk_seconds:g}s =========="
        )
        plans = _build_source_plans(chunk_seconds)
        all_source_paths = [
            path for plan in plans for path in plan["wav_paths"]
        ]
        print("Resolving the shared noise reference RMS...")
        global_reference_rms, rms_by_path, reference_records, reference_provenance = _resolve_reference_rms(
            all_source_paths
        )
        print(f"global_reference_rms={global_reference_rms:.10g}")

        for exp_i, plan in enumerate(plans, start=1):
            experiment_name = plan["experiment_name"]
            wav_files = plan["wav_files"]
            wav_paths = plan["wav_paths"]
            discovery_context = plan["context"]
            label_count = len(
                discovery_context["heat_flux_label_by_index"]
            )
            if label_count and label_count != len(wav_files):
                print(
                    f"Warning: heat flux labels={label_count}, "
                    f"wav files={len(wav_files)} in {experiment_name}"
                )

            print(
                f"========== experiment {exp_i}/{len(plans)}: "
                f"{experiment_name} | wav={len(wav_files)} =========="
            )
            print("Preloading and filtering source WAVs...")
            filtered_signal_by_path = {
                path: _load_and_filter(path) for path in wav_paths
            }

            context = discovery_context
            generation_config = {
                **PREPROCESS_CONFIG,
                "fixed_reference_signal_rms": global_reference_rms,
                "fixed_reference_provenance": reference_provenance,
                "reference_source_manifests": reference_records,
            }
            _write_reference_manifest(
                context, global_reference_rms, rms_by_path, reference_records
            )

            for max_freq_hz in MAX_FREQ_HZ:
                print(f"----- max_freq_hz={max_freq_hz} -----")
                for wav_i, (filename, file_path) in enumerate(
                    zip(wav_files, wav_paths), start=1
                ):
                    save_spectrogram_chunks_with_snr(
                        file_path=file_path,
                        max_freq_hz=max_freq_hz,
                        chunk_seconds=chunk_seconds,
                        context=context,
                        config=generation_config,
                        snr_db=REFERENCE_SNR_DB,
                        prefiltered_signal=filtered_signal_by_path[
                            file_path
                        ],
                        prefiltered_waterflow_noise=(
                            filtered_waterflow_noise
                        ),
                    )
                    print(
                        f"---------- {wav_i} / {len(wav_files)} "
                        f"({filename}) done! ----------"
                    )

            del filtered_signal_by_path

    print("---------- All experiments done! ----------")


if __name__ == "__main__":
    run_all_experiments()
